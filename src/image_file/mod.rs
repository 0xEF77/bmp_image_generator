//! BMP 文件相关模块。
//!
//! 按照 BMP 规范，一张未压缩的位图在字节层面由下面几部分组成，本模块把它们分别
//! 拆成独立的子模块，最后再组合成完整的文件：
//!
//! ```text
//! +------------------+ 14 字节
//! | 文件头           |  文件类型、总大小、像素数据偏移量
//! +------------------+ 40 字节
//! | 信息头           |  宽高、位深、压缩方式等
//! +------------------+ 0 字节（24/32 位图不使用调色板）
//! | 调色板           |
//! +------------------+
//! | 像素数据         |  本实现按 BGR 顺序逐个像素写入
//! +------------------+
//! ```
//!
//! 子模块分工：
//!
//! - [`bitmap`]：把四个部分组合成一张完整的图像
//! - [`file_info`]：文件头、信息头与调色板的结构与序列化
//! - [`pixels_data`]：单个像素与像素数据容器的结构与序列化
//! - [`create_image`]：面向调用者的创建、填充与序列化入口
pub mod bitmap;
pub mod create_image;
pub mod file_info;
pub mod pixels_data;
